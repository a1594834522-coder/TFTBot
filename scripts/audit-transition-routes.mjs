import fs from 'node:fs';
import path from 'node:path';
import {build} from 'esbuild';
import {pathToFileURL} from 'node:url';
const root=path.resolve(import.meta.dirname,'..');
const output=path.join(root,'dist/transition-analysis');
fs.mkdirSync(output,{recursive:true});
await build({entryPoints:[path.join(root,'src/game/early-transition-graph.ts')],outfile:path.join(output,'adapter.mjs'),bundle:true,platform:'node',format:'esm'});
const {observedRoutes}=await import(pathToFileURL(path.join(output,'adapter.mjs')));
const graph=JSON.parse(fs.readFileSync(path.join(root,'data/metatft-transitions.json'),'utf8'));
const catalog=JSON.parse(fs.readFileSync(path.join(root,'data/tft-sets.json'),'utf8'));
const names=new Map(catalog.characters['18'].map(h=>[h.character_id,h.display_name]));
const nodes=new Map(graph.nodes.map(n=>[n.id,n]));
const labels=id=>nodes.get(id).units.map(u=>names.get(u)??u);
const zero=graph.edges.filter(e=>e.current?.battleWeight>=30&&e.current.avgPlace<4.5&&nodes.get(e.from).units.every(u=>!nodes.get(e.to).units.includes(u))).sort((a,b)=>b.current.battleWeight-a.current.battleWeight);
const examples=zero.slice(0,12).map(e=>({from:e.from,fromUnits:labels(e.from),to:e.to,toUnits:labels(e.to),...e.current}));
const chains=observedRoutes(graph,'early-2-0',5,{minimumWeight:30,beam:100}).slice(0,5).map(r=>({...r,labels:r.nodes.map(labels)}));
const report={clusteringId:graph.meta.clusteringId,updated:graph.meta.overviewUpdated,nodes:graph.nodes.length,edges:graph.edges.length,zeroOverlapWithWeight30AndMeanBelow4_5:zero.length,warning:'Observational fractional weights, not games. Multi-stage chains use a Markov approximation; no chain outcome is asserted.',examples,chains};
fs.writeFileSync(path.join(output,'route-audit.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({nodes:report.nodes,edges:report.edges,zeroOverlap:zero.length,example:examples[4],topChain:chains[0]?.labels,report:path.join(output,'route-audit.json')},null,2));
